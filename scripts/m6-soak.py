def summarize_rows(rows: list[tuple], kind: str | None = None, phase: str | None = None) -> dict:
    sel = [r for r in rows if (kind is None or r[1] == kind) and (phase is None or r[3] == phase)]
    ok_lat = [r[4] for r in sel if r[8] == 1]
    codes: dict[str, int] = {}
    for r in sel:
        if r[8] != 1:
            key = r[6] or f"HTTP_{r[5]}"
            if r[7]:
                key += f"/{r[7]}"
            if key.startswith("HTTP_") and len(r) > 9 and r[9]:
                key += f" [{r[9][:48]}]"
            codes[key] = codes.get(key, 0) + 1
    span = (max(r[0] for r in sel) - min(r[0] for r in sel)) if len(sel) > 1 else 0
    return {
        "requests": len(sel), "ok": len(ok_lat), "errors": len(sel) - len(ok_lat),
        "errors_by_code": dict(sorted(codes.items(), key=lambda kv: -kv[1])),
        "latency_ms_ok": {"p50": percentile(ok_lat, 50), "p95": percentile(ok_lat, 95),
                          "p99": percentile(ok_lat, 99), "max": max(ok_lat) if ok_lat else None,
                          "mean": round(statistics.fmean(ok_lat), 2) if ok_lat else None},
        "throughput_ok_per_s": round(len(ok_lat) / span, 2) if span else None,
    }


def summarize_samples(path: Path) -> dict:
    out: dict[str, dict] = {}
    if not path.exists():
        return out
    rows = [line for line in path.read_text().splitlines() if not line.startswith("#")]
    reader = csv.DictReader(rows)
    series: dict[str, list[dict]] = {}
    for row in reader:
        series.setdefault(row["process"], []).append(row)
    loads = [float(r["load1"]) for items in series.values() for r in items if r.get("load1")]
    if loads:
        out["host_load1"] = {"min": min(loads), "mean": round(statistics.fmean(loads), 2),
                             "max": max(loads),
                             "samples_above_20": sum(1 for x in loads if x > 20),
                             "samples": len(loads)}
    for name, items in series.items():
        rss = [int(r["rss_kib"]) for r in items if r["rss_kib"].isdigit()]
        fds = [int(r["fds"]) for r in items if r["fds"].isdigit()]
        entry = {"samples": len(items)}
        if rss:
            n = len(rss)
            q = max(1, n // 4)
            entry.update({"rss_kib_first": rss[0], "rss_kib_last": rss[-1], "rss_kib_min": min(rss),
                          "rss_kib_max": max(rss),
                          "rss_kib_mean_second_quarter": round(statistics.fmean(rss[q:2 * q]) if n >= 4 else rss[0]),
                          "rss_kib_mean_last_quarter": round(statistics.fmean(rss[-q:]))})
        if fds:
            entry.update({"fds_first": fds[0], "fds_last": fds[-1], "fds_min": min(fds),
                          "fds_max": max(fds)})
        if name == "relay":
            for series_name in ("tunnel_relay_device_sockets", "tunnel_relay_streams",
                                "tunnel_relay_queue_bytes", "tunnel_relay_replay_bytes",
                                "tunnel_relay_sessions_rotating"):
                vals = [float(r[series_name]) for r in items if r.get(series_name)]
                if vals:
                    entry[f"{series_name}_max"] = max(vals)
                    entry[f"{series_name}_last"] = vals[-1]
            for counter in ("tunnel_relay_consumer_refusals_total",
                            "tunnel_relay_consumer_write_timeouts_total"):
                vals = [float(r[counter]) for r in items if r.get(counter)]
                if vals:
                    entry[f"{counter}_last"] = vals[-1]
        out[name] = entry
    return out


