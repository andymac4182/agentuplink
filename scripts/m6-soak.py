def scrape_metrics(port: int) -> dict[str, float]:
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=3) as sock:
            sock.sendall(b"GET /metrics HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n")
            data = b""
            while True:
                chunk = sock.recv(65536)
                if not chunk:
                    break
                data += chunk
    except OSError:
        return {}
    values: dict[str, float] = {}
    for line in data.decode(errors="replace").splitlines():
        if line.startswith("#"):
            continue
        parts = line.rsplit(" ", 1)
        if len(parts) != 2:
            continue
        name = parts[0].split("{", 1)[0]
        if name in METRIC_SERIES:
            try:
                values[name] = values.get(name, 0.0) + float(parts[1])
            except ValueError:
                pass
    return values


class Sampler(threading.Thread):
    def __init__(self, stack: Stack, interval: float = 15.0, fd_every: int = 4):
        super().__init__(daemon=True)
        self.stack = stack
        self.interval = interval
        self.fd_every = fd_every
        self.stop_flag = threading.Event()
        self.path = stack.run_dir / "samples.csv"
        self.handle = self.path.open("w", newline="")
        self.handle.write(f"# nonce={stack.nonce} head={head_sha()} samples\n")
        self.writer = csv.writer(self.handle)
        self.writer.writerow(["t", "load1", "process", "pid", "rss_kib", "fds", *METRIC_SERIES])

    def run(self) -> None:
        tick = 0
        while not self.stop_flag.is_set():
            procs = [("relay", self.stack.relay), ("forwarder", self.stack.forwarder)]
            procs += [(f"device-{n}", d.get("proc")) for n, d in self.stack.devices.items()]
            metrics = scrape_metrics(self.stack.metrics_port) if hasattr(self.stack, "metrics_port") else {}
            now = round(time.time(), 1)
            for name, proc in procs:
                if not proc or proc.poll() is not None:
                    continue
                fds = fd_count(proc.pid) if tick % self.fd_every == 0 else ""
                row = [now, round(os.getloadavg()[0], 2), name, proc.pid, rss_kib(proc.pid), fds]
                row += [metrics.get(s, "") if name == "relay" else "" for s in METRIC_SERIES]
                self.writer.writerow(row)
            self.handle.flush()
            tick += 1
            self.stop_flag.wait(self.interval)

    def stop(self) -> None:
        self.stop_flag.set()
        self.join(timeout=30)
        self.handle.close()


