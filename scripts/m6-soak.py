#!/usr/bin/env python3
"""Task row M6-03: soak, load, chaos and fairness experiments against a local
relay and synthetic devices, driven through the shipped binaries.

    scripts/m6-soak.py soak     --bin-dir DIR --logs DIR [--duration 7200]
    scripts/m6-soak.py load     --bin-dir DIR --logs DIR
    scripts/m6-soak.py chaos    --bin-dir DIR --logs DIR
    scripts/m6-soak.py fairness --bin-dir DIR --logs DIR
    scripts/m6-soak.py summarize --logs DIR --run RUN_DIR

Every experiment brings up its own stack from an empty Redis namespace with
the same shipped commands the operator guide uses (`credentials create`,
`credentials import`, `activate-first-incarnation`, `provision-catalog`,
`add-user`, `add-device`, `add-service`, `set-grant`, `serve`, `connect`).
Every consumer request goes device -> relay -> consumer over real TLS
sockets; nothing bypasses the relay.

Redis: `soak`, `load` and `fairness` use the shared plaintext Redis
(`--redis`, default 127.0.0.1:63790) under a unique namespace, fronted by a
TLS forwarder child process, and delete the namespace on exit.  `chaos`
starts its OWN throwaway `redis:8.4.0-alpine` container (named
`m6-03-soak-chaos-<nonce>`), because it pauses Redis; it never pauses,
restarts or reads another container, and removes its container on exit.

Output: one run directory per invocation under `--logs`, holding
`requests.csv` (one row per consumer request: wall time, kind, worker,
latency, HTTP status, error code, execution class, integrity), `samples.csv`
(RSS and open file descriptors of the relay, devices and forwarder, and the
relay's metrics gauges, over time), `events.jsonl` (faults, phases, device
sessions and rotations) and `summary.json`.  The first line of every log
carries the run nonce and `head=<sha>`.

Synthetic data only: payloads are generated bytes, tokens are signed by a
throwaway issuer key and never written to a log.
"""

