class Recorder:
    FIELDS = ["t", "kind", "worker", "phase", "latency_ms", "status", "code", "execution", "ok",
              "detail"]

    def __init__(self, path: Path, nonce: str):
        self.handle = path.open("w", newline="")
        self.handle.write(f"# nonce={nonce} head={head_sha()} requests\n")
        self.writer = csv.writer(self.handle)
        self.writer.writerow(self.FIELDS)
        self.rows: list[tuple] = []
        self.phase = "run"
        self.count = 0

    def add(self, t, kind, worker, latency_ms, status, code, execution, ok, detail=""):
        row = (round(t, 3), kind, worker, self.phase, round(latency_ms, 2), status, code,
               execution, int(ok), detail)
        self.writer.writerow(row)
        self.rows.append(row)
        self.count += 1
        if self.count % 200 == 0:
            self.handle.flush()

    def close(self) -> None:
        self.handle.flush()
        self.handle.close()


class HttpConn:
    """A minimal keep-alive HTTP/1.1 client over TLS (stdlib only)."""

    def __init__(self, port: int, ctx: ssl.SSLContext):
        self.port, self.ctx = port, ctx
        self.reader = self.writer = None

    async def ensure(self) -> None:
        if self.writer is None:
            self.reader, self.writer = await asyncio.open_connection(
                "127.0.0.1", self.port, ssl=self.ctx, server_hostname="localhost")

    async def close(self) -> None:
        if self.writer is not None:
            try:
                self.writer.close()
            except Exception:  # noqa: BLE001
                pass
        self.reader = self.writer = None

    async def request(self, method: str, path: str, headers: dict[str, str],
                      body: bytes) -> tuple[int, dict[str, str], bytes]:
        await self.ensure()
        head = f"{method} {path} HTTP/1.1\r\nHost: localhost\r\nContent-Length: {len(body)}\r\n"
        head += "".join(f"{k}: {v}\r\n" for k, v in headers.items()) + "\r\n"
        self.writer.write(head.encode() + body)
        await self.writer.drain()
        status_line = await self.reader.readline()
        if not status_line:
            raise ConnectionError("closed before status")
        status = int(status_line.split()[1])
        response_headers: dict[str, str] = {}
        while True:
            line = await self.reader.readline()
            if line in (b"\r\n", b"\n", b""):
                break
            name, _, value = line.decode("latin-1").partition(":")
            response_headers[name.strip().lower()] = value.strip()
        data = b""
        if status in (204, 304) or 100 <= status < 200:
            pass  # no body by definition (a DELETE answers 204 without Content-Length)
        elif response_headers.get("transfer-encoding", "").lower() == "chunked":
            while True:
                size = int((await self.reader.readline()).split(b";")[0].strip(), 16)
                if size == 0:
                    await self.reader.readline()
                    break
                data += await self.reader.readexactly(size)
                await self.reader.readexactly(2)
        elif "content-length" in response_headers:
            data = await self.reader.readexactly(int(response_headers["content-length"]))
        else:
            data = await self.reader.read()
            await self.close()
        if response_headers.get("connection", "").lower() == "close":
            await self.close()
        return status, response_headers, data


def classify(status: int, body: bytes) -> tuple[str, str]:
    if status == 200:
        return "", ""
    # The relay's flat-body routes answer {"code","execution",...}; the
    # http-forward gateway nests the same pair under "error".
    try:
        value = json.loads(body)
    except ValueError:
        value = None
    if isinstance(value, dict):
        error = value.get("error") if isinstance(value.get("error"), dict) else value
        if "code" in error:
            return str(error["code"]), str(error.get("execution", ""))
    return f"HTTP_{status}", ""


def client_ctx(stack: Stack) -> ssl.SSLContext:
    ctx = ssl.create_default_context(cafile=str(stack.work / "server-ca.pem"))
    ctx.verify_flags &= ~getattr(ssl, "VERIFY_X509_STRICT", 0)
    return ctx


class McpSessionPool:
    """2025-11-25 MCP sessions shared by one or more workers (M6-C146).

    A stdio export holds one child, and one of its `max_children` slots
    (default 8), per session until `DELETE`, a child crash or the 600 s
    `session_idle_seconds`.  Workers therefore share a bounded number of
    sessions (concurrent POSTs on one session are routed by JSON-RPC ID) and
    whoever owns the pool DELETEs every session it opened when it is done, so
    a load step measures concurrent MCP calls instead of the leaked-session
    bound.  A session is dropped from the pool only on 404 (the export no
    longer knows it); a timeout or connection error resets the worker's
    connection, never the session, so it is not orphaned.  A session whose
    `notifications/initialized` failed is not usable: it is DELETEd at once or,
    if that fails, kept in `orphans` so `close` DELETEs it.  `stats` accounts
    for every opened session: deleted, a recorded DELETE failure, or forgotten
    on 404; anything else is `unaccounted`.
    """

    def __init__(self, size: int):
        self.sessions: list[str | None] = [None] * max(1, size)
        self.locks = [asyncio.Lock() for _ in self.sessions]
        self.opened = 0
        self.deleted = 0
        self.delete_failures: dict[str, int] = {}
        self.orphans: list[str] = []
        self.forgotten_on_404 = 0
        self.init_timeouts = 0

    def forget(self, slot: int, session: str) -> None:
        if self.sessions[slot] == session:
            self.sessions[slot] = None
            self.forgotten_on_404 += 1

    async def close(self, worker: "Worker", attempts: int = 3) -> None:
        """DELETE every open session through `worker`'s connection.

        A reset keep-alive connection or a retryable `503` (for example
        `CONNECTION_LIMIT`) is retried on a fresh connection, so a session is
        left to the export's idle expiry only after `attempts` failures.
        """
        pending = [x for x in self.sessions if x is not None] + self.orphans
        self.sessions = [None] * len(self.sessions)
        self.orphans = []
        for session in pending:
            key = ""
            for attempt in range(attempts):
                if attempt:
                    await asyncio.sleep(1.0)
                try:
                    status = await worker.delete_mcp_session(session)
                except (asyncio.TimeoutError, TimeoutError, OSError, ConnectionError,
                        asyncio.IncompleteReadError, ssl.SSLError, ValueError,
                        IndexError) as error:
                    await worker.conn.close()
                    key = f"CONN_{type(error).__name__}"
                    continue
                if status in (200, 202, 204):
                    self.deleted += 1
                    key = ""
                    break
                if status == 404:
                    key = "HTTP_404"  # already gone (crash or idle expiry)
                    break
                key = f"HTTP_{status}"
                if status != 503:
                    break
            if key:
                self.delete_failures[key] = self.delete_failures.get(key, 0) + 1

    def stats(self) -> dict:
        failures = sum(self.delete_failures.values())
        return {"size": len(self.sessions), "opened": self.opened, "deleted": self.deleted,
                "delete_failures": dict(self.delete_failures),
                "forgotten_on_404": self.forgotten_on_404,
                "init_timeouts": self.init_timeouts,
                "unaccounted": self.opened - self.deleted - failures - self.forgotten_on_404}

    def leaked(self) -> bool:
        """True if a session may still hold an export slot after `close`."""
        # Only a 404 proves the session is gone; any other DELETE failure, and
        # an initialize whose session ID never arrived, may hold a slot.
        stats = self.stats()
        return (stats["unaccounted"] != 0 or self.init_timeouts > 0
                or any(key != "HTTP_404" for key in self.delete_failures))


def report_mcp_pool(stack: "Stack", pool: McpSessionPool, where: str) -> None:
    """Make a possibly leaked session visible in the driver log (M6-C146)."""
    if pool.leaked():
        stack.event("mcp-session-leak", where=where, mcp_sessions=pool.stats())


class Worker:
    """One consumer: one keep-alive connection, echo or MCP tools/call."""

    def __init__(self, stack: Stack, rec: Recorder, kind: str, user: str, device: str,
                 worker_id: str, payload_size: int = 1024,
                 mcp_pool: McpSessionPool | None = None, mcp_slot: int = 0):
        self.stack, self.rec, self.kind, self.user, self.device = stack, rec, kind, user, device
        self.worker_id = worker_id
        self.payload_size = payload_size
        self.conn = HttpConn(stack.consumer_port, client_ctx(stack))
        self.seq = 0
        # A worker without a shared pool owns a private one-session pool and
        # DELETEs that session at shutdown.
        self.owns_pool = mcp_pool is None
        self.mcp_pool = mcp_pool if mcp_pool is not None else McpSessionPool(1)
        self.mcp_slot = mcp_slot % len(self.mcp_pool.sessions)
        self.mcp_calls_ok = 0
        # M6-C182: with `honor_retry_after`, a closed-loop worker refused
        # `CONNECTION_LIMIT` waits the refusal's `retry_after_ms` before its
        # next request instead of reconnecting at once.
        self.honor_retry_after = False
        self.retry_after_s = 0.0

    def path(self) -> str:
        dev = self.stack.devices[self.device]
        if self.kind == "echo":
            return f"/v1/devices/{dev['id']}/services/{dev['echo']}/echo"
        return f"/v1/devices/{dev['id']}/services/{dev['mcp']}/http/mcp"

    async def call(self, method: str, headers: dict, body: bytes, timeout: float = 40.0):
        return await asyncio.wait_for(self.conn.request(method, self.path(), headers, body), timeout)

    async def once(self) -> None:
        self.seq += 1
        t0 = time.time()
        body = b""
        start = time.perf_counter()
        user = self.stack.users[self.user]["subject"]
        try:
            if self.kind == "echo":
                token = await asyncio.to_thread(self.stack.token, user, "echo:invoke")
                payload = (f"{self.worker_id}:{self.seq}:".encode() * (self.payload_size // 8 + 1)
                           )[: self.payload_size]
                status, _, body = await self.call("POST", {
                    "Authorization": f"Bearer {token}",
                    "Content-Type": "application/octet-stream"}, payload)
                code, execution = classify(status, body)
                ok = status == 200 and body == CANARY + payload
                if status == 200 and not ok:
                    code = "INTEGRITY_MISMATCH"
            else:
                token = await asyncio.to_thread(self.stack.token, user, "http:invoke")
                status, body, code, execution, ok = await self.mcp_call(token)
        except (asyncio.TimeoutError, TimeoutError):
            await self.conn.close()
            status, code, execution, ok = 0, "CLIENT_TIMEOUT", "unknown", False
        except (OSError, ConnectionError, asyncio.IncompleteReadError, ssl.SSLError, ValueError,
                IndexError) as error:
            await self.conn.close()
            status, code, execution, ok = 0, f"CONN_{type(error).__name__}", "", False
        latency = (time.perf_counter() - start) * 1000
        if code == "CONNECTION_LIMIT":
            try:
                self.retry_after_s = float(json.loads(body).get("retry_after_ms", 1000)) / 1000
            except (ValueError, AttributeError):
                self.retry_after_s = 1.0
        # An unclassified refusal keeps a short printable prefix of its body
        # (a relay or fixture error text, never a request payload).
        detail = ""
        if code.startswith("HTTP_") and status and status != 200:
            detail = re.sub(r"[^ -~]", "?", body[:80].decode("latin-1"))
        self.rec.add(t0, self.kind, self.worker_id, latency, status, code, execution, ok, detail)

    def mcp_headers(self, token: str) -> dict:
        return {"Authorization": f"Bearer {token}", "Content-Type": "application/json",
                "Accept": "application/json, text/event-stream"}

    async def mcp_initialize(self, base: dict):
        """Open one session; returns (session, None) or (None, failure tuple)."""
        init = json.dumps({"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
            "protocolVersion": "2025-11-25", "capabilities": {},
            "clientInfo": {"name": "m6-03-soak", "version": "1"}}}).encode()
        try:
            status, headers, body = await self.call("POST", base, init)
        except (asyncio.TimeoutError, TimeoutError):
            # The export may have opened a session whose ID never arrived; only
            # its idle expiry can end it.  Counted so the step shows it.
            self.mcp_pool.init_timeouts += 1
            raise
        if status != 200 or "mcp-session-id" not in headers:
            code, execution = classify(status, body)
            return None, (status, body, code or "MCP_INIT_NO_SESSION", execution, False)
        session = headers["mcp-session-id"]
        self.mcp_pool.opened += 1
        hdrs = {**base, "mcp-protocol-version": "2025-11-25", "mcp-session-id": session}
        try:
            status, _, body = await self.call(
                "POST", hdrs, b'{"jsonrpc":"2.0","method":"notifications/initialized"}')
        except BaseException:
            # A timeout or connection error here must not orphan the session:
            # the pool's close DELETEs it.  The caller records the error.
            self.mcp_pool.orphans.append(session)
            raise
        if status != 202:
            # Not usable: DELETE it rather than leave it holding a child slot;
            # if that fails, the pool's close tries again.
            deleted = False
            try:
                deleted = await self.delete_mcp_session(session) in (200, 202, 204)
            except (asyncio.TimeoutError, TimeoutError, OSError, ConnectionError,
                    asyncio.IncompleteReadError, ssl.SSLError, ValueError, IndexError):
                await self.conn.close()
            if deleted:
                self.mcp_pool.deleted += 1
            else:
                self.mcp_pool.orphans.append(session)
            code, execution = classify(status, body)
            return None, (status, body, code, execution, False)
        return session, None

    async def delete_mcp_session(self, session: str) -> int:
        token = await asyncio.to_thread(self.stack.token, self.stack.users[self.user]["subject"],
                                        "http:invoke")
        hdrs = {"Authorization": f"Bearer {token}", "mcp-protocol-version": "2025-11-25",
                "mcp-session-id": session}
        status, _, _ = await self.call("DELETE", hdrs, b"", timeout=15.0)
        return status

    async def mcp_call(self, token: str):
        base = self.mcp_headers(token)
        pool, slot = self.mcp_pool, self.mcp_slot
        session = pool.sessions[slot]
        if session is None:
            async with pool.locks[slot]:
                session = pool.sessions[slot]
                if session is None:
                    session, failure = await self.mcp_initialize(base)
                    if failure is not None:
                        return failure
                    pool.sessions[slot] = session
        hdrs = {**base, "mcp-protocol-version": "2025-11-25", "mcp-session-id": session}
        marker = f"{self.worker_id}-{self.seq}"
        call = json.dumps({"jsonrpc": "2.0", "id": marker, "method": "tools/call",
                           "params": {"name": "echo", "arguments": {"marker": marker}}}).encode()
        status, _, body = await self.call("POST", hdrs, call)
        code, execution = classify(status, body)
        ok = False
        if status == 200:
            text = body.decode(errors="replace")
            if "data:" in text and "{" in text:
                text = text[text.index("{"):]
            ok = marker in text
            if not ok:
                code = "INTEGRITY_MISMATCH"
            else:
                self.mcp_calls_ok += 1
        elif status == 404:
            pool.forget(slot, session)
        return status, body, code, execution, ok

    async def loop_rate(self, rate: float, until: float) -> None:
        interval = 1.0 / rate
        next_at = time.time()
        while time.time() < until:
            await self.once()
            next_at += interval
            delay = next_at - time.time()
            if delay > 0:
                await asyncio.sleep(delay)
            else:
                next_at = time.time()

    async def loop_closed(self, until: float) -> None:
        while time.time() < until:
            await self.once()
            if self.honor_retry_after and self.retry_after_s:
                await asyncio.sleep(min(self.retry_after_s, max(0.0, until - time.time())))
            self.retry_after_s = 0.0

    async def shutdown(self) -> None:
        if self.owns_pool:
            await self.mcp_pool.close(self)
            if self.kind == "mcp":
                report_mcp_pool(self.stack, self.mcp_pool, self.worker_id)
        await self.conn.close()


# ------------------------------------ generator attribution (M6-C182, M6-C183)
#
# Every in-process worker shares this driver's single asyncio event loop (and
# its one Python thread).  A request's latency is measured on that loop, so it
# includes the time the loop spends running every other worker's callbacks.
# The helpers below separate the generator from the relay: `LoopLag` measures
# the driver loop's own scheduling delay, `cpu_seconds` accounts each process's
# CPU, and `start_clients` runs workers in separate `client` subprocesses, each
# with its own loop, so the same request code is timed off the flooding loop.

def cpu_seconds(pid: int) -> float | None:
    """Cumulative user + system CPU seconds of one process (no payload)."""
    stat = Path(f"/proc/{pid}/stat")
    if stat.exists():  # Linux: tick resolution
        try:
            fields = stat.read_text().rsplit(")", 1)[1].split()
            return (int(fields[11]) + int(fields[12])) / os.sysconf("SC_CLK_TCK")
        except (OSError, IndexError, ValueError):
            return None
    out = subprocess.run(["ps", "-o", "time=", "-p", str(pid)], capture_output=True, text=True)
    text = out.stdout.strip()
    if not text:
        return None
    days, _, clock = text.rpartition("-")
    total = 0.0
    for part in clock.split(":"):
        total = total * 60 + float(part)
    return total + (int(days) * 86400 if days else 0)


def cpu_snapshot(stack: Stack) -> tuple[float, dict[str, float]]:
    procs = [("relay", stack.relay), ("forwarder", stack.forwarder)]
    procs += [(f"device-{n}", d.get("proc")) for n, d in stack.devices.items()]
    out: dict[str, float] = {}
    for name, proc in procs:
        if proc is not None and proc.poll() is None:
            value = cpu_seconds(proc.pid)
            if value is not None:
                out[name] = value
    own = os.times()
    out["driver"] = own.user + own.system
    out.update(redis_counters(stack.redis))
    metrics = scrape_metrics(stack.metrics_port) if hasattr(stack, "metrics_port") else {}
    if "tunnel_relay_actor_busy_microseconds_total" in metrics:
        out["relay_actor"] = metrics["tunnel_relay_actor_busy_microseconds_total"] / 1e6
        out["relay_actor_commands"] = metrics.get("tunnel_relay_actor_commands_total", 0.0)
    return time.perf_counter(), out


def redis_counters(redis: tuple[str, int]) -> dict[str, float]:
    """The Redis server's CPU seconds and script/command totals (INFO; no
    keys or values).  On a shared Redis these include other clients' work."""
    try:
        text = resp(redis[0], redis[1], ["INFO", "all"]).decode(errors="replace")
    except OSError:
        return {}
    out: dict[str, float] = {}
    for line in text.splitlines():
        name, _, value = line.partition(":")
        if name in ("used_cpu_sys", "used_cpu_user"):
            out["redis"] = out.get("redis", 0.0) + float(value)
        elif name == "total_commands_processed":
            out["redis_commands"] = float(value)
        elif name.startswith("cmdstat_eval"):
            fields = dict(item.split("=", 1) for item in value.split(",") if "=" in item)
            out["redis_script_calls"] = out.get("redis_script_calls", 0.0) + float(fields.get("calls", 0))
            out["redis_script_usec"] = out.get("redis_script_usec", 0.0) + float(fields.get("usec", 0))
    return out


def cpu_percent(before: tuple[float, dict[str, float]],
                after: tuple[float, dict[str, float]]) -> dict[str, float]:
    """CPU use per process over an interval, in percent of one CPU (for
    `relay_actor`, the single relay actor's busy wall time in percent); Redis
    and relay actor command counts as rates per second, and script time per
    call."""
    span = after[0] - before[0]
    if span <= 0:
        return {}
    delta = {name: after[1][name] - before[1][name] for name in after[1] if name in before[1]}
    out = {}
    for name, value in delta.items():
        if name in ("redis_commands", "redis_script_calls", "relay_actor_commands"):
            out[f"{name}_per_s"] = round(value / span, 1)
        elif name != "redis_script_usec":
            out[name] = round(value / span * 100, 1)
    if delta.get("redis_script_calls"):
        out["redis_script_usec_per_call"] = round(delta.get("redis_script_usec", 0.0)
                                                  / delta["redis_script_calls"], 1)
    return out


class LoopLag:
    """How late a 10 ms sleep wakes on this process's event loop.  With a
    saturated loop, every request timed on it is delayed by about this much."""

    def __init__(self, interval: float = 0.01):
        self.interval = interval
        self.samples: list[float] = []

    async def run(self, until: float) -> None:
        while time.time() < until:
            start = time.perf_counter()
            await asyncio.sleep(self.interval)
            self.samples.append((time.perf_counter() - start - self.interval) * 1000)

    def summary(self) -> dict:
        def pct(value: float) -> float | None:
            found = percentile(self.samples, value)
            return None if found is None else round(found, 2)
        return {"samples": len(self.samples), "p50": pct(50), "p99": pct(99),
                "max": round(max(self.samples), 2) if self.samples else None}


class _ClientStack:
    """The subset of `Stack` a `Worker` uses, for a `client` subprocess."""

    def __init__(self, cfg: dict):
        self.consumer_port = cfg["port"]
        self.work = Path(cfg["work"])
        self.users = {"u": {"subject": cfg["subject"]}}
        self.devices = {"d": {"id": cfg["device_id"], "echo": cfg["echo"]}}
        self._token = cfg["token"]

    def token(self, subject: str, scope: str) -> str:
        return self._token


async def client_main_async(cfg: dict) -> dict:
    stack = _ClientStack(cfg)
    rec = Recorder(Path(cfg["csv"]), cfg["nonce"])
    rec.phase = cfg["phase"]
    workers = [Worker(stack, rec, "echo", "u", "d", f"{cfg['prefix']}-{i}",
                      payload_size=cfg["payload"]) for i in range(cfg["workers"])]
    for w in workers:
        w.honor_retry_after = bool(cfg.get("honor_retry_after"))
    if cfg.get("preconnect"):
        # Open (and hold) each keep-alive connection before the caller starts
        # anything else, so this client is measured as an already-connected
        # consumer rather than one competing for a listener permit.
        for w in workers:
            await asyncio.wait_for(w.conn.ensure(), 30)
    print(json.dumps({"ready": True}), flush=True)
    lag = LoopLag()
    until = cfg["until"]
    loops = [w.loop_rate(cfg["rate"], until) if cfg["rate"] else w.loop_closed(until)
             for w in workers]
    await asyncio.gather(lag.run(until), *loops)
    for w in workers:
        await w.shutdown()
    rec.close()
    own = os.times()
    return {"rows": rec.count, "loop_lag_ms": lag.summary(),
            "cpu_s": round(own.user + own.system, 3)}


def client_main() -> None:
    """`client`: echo workers on this process's own event loop.  The
    configuration, including the token, arrives on stdin, never in argv; one
    JSON summary line is printed on stdout."""
    cfg = json.loads(sys.stdin.read())
    print(json.dumps(asyncio.run(client_main_async(cfg))), flush=True)


async def start_clients(stack: Stack, rec: Recorder, user: str, device: str, prefix: str,
                        workers: int, processes: int, until: float, rate: float = 0.0,
                        payload: int = 1024, preconnect: bool = False,
                        honor_retry_after: bool = False):
    """Start `workers` echo workers split across `processes` `client`
    subprocesses, running until `until`, and return once every process is
    ready (with `preconnect`, once its connections are open).  Await the
    returned coroutine to merge their rows into `rec` under the current
    phase; it returns each process's loop lag and CPU seconds."""
    dev = stack.devices[device]
    # A client process holds one token for its whole run (it cannot re-sign),
    # so it must outlive `until` with the usual 60 s margin.
    token = await asyncio.to_thread(stack.token, stack.users[user]["subject"], "echo:invoke",
                                    max(0.0, until - time.time()) + 60)
    shares = [workers // processes + (1 if i < workers % processes else 0)
              for i in range(processes)]
    procs = []
    for index, share in enumerate(s for s in shares if s):
        csv_path = stack.run_dir / f"client-{prefix}-{index}.csv"
        cfg = {"port": stack.consumer_port, "work": str(stack.work),
               "subject": stack.users[user]["subject"], "device_id": dev["id"],
               "echo": dev["echo"], "token": token, "csv": str(csv_path), "nonce": stack.nonce,
               "phase": rec.phase, "prefix": f"{prefix}-p{index}", "workers": share,
               "rate": rate, "payload": payload, "until": until, "preconnect": preconnect,
               "honor_retry_after": honor_retry_after}
        proc = await asyncio.create_subprocess_exec(
            sys.executable, str(Path(__file__).resolve()), "client",
            stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE,
            start_new_session=True)
        proc.stdin.write(json.dumps(cfg).encode())
        await proc.stdin.drain()
        proc.stdin.close()
        procs.append((proc, csv_path))
    for proc, _ in procs:
        await asyncio.wait_for(proc.stdout.readline(), 60)  # {"ready": true}
    return _finish_clients(rec, procs)


async def _finish_clients(rec: Recorder, procs: list) -> dict:
    results = await asyncio.gather(*(p.communicate() for p, _ in procs))
    report = []
    for (proc, csv_path), (stdout, _) in zip(procs, results):
        lines = [line for line in csv_path.read_text().splitlines() if not line.startswith("#")]
        for row in list(csv.DictReader(lines)):
            rec.add(float(row["t"]), row["kind"], row["worker"], float(row["latency_ms"]),
                    int(row["status"]), row["code"], row["execution"], row["ok"] == "1",
                    row["detail"])
        try:
            summary = json.loads(stdout.decode().strip().splitlines()[-1])
        except (ValueError, IndexError):
            summary = {"error": f"client exited {proc.returncode} without a summary"}
        summary["exit"] = proc.returncode
        report.append(summary)
    return {"processes": report}


async def wait_serving(stack: Stack, rec: Recorder, device: str = "a", user: str = "a",
                       kind: str = "echo", timeout: float = 60) -> float:
    """Seconds until the first 200 through the relay; warm-up rows are phase=warmup."""
    phase, rec.phase = rec.phase, "warmup"
    worker = Worker(stack, rec, kind, user, device, f"warm-{device}-{kind}")
    start = time.time()
    try:
        while time.time() - start < timeout:
            before = len(rec.rows)
            await worker.once()
            if rec.rows[before][5] == 200:
                return time.time() - start
            await asyncio.sleep(0.2)
        raise SystemExit(f"device {device} not serving {kind} within {timeout} s")
    finally:
        await worker.shutdown()
        rec.phase = phase


