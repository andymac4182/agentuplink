# ---------------------------------------------------------------- utilities

def now_iso() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%S%z")


def head_sha() -> str:
    try:
        return subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def run(args: list[str], cwd: Path | None = None, stdin: bytes | None = None,
        check: bool = True, timeout: float = 120) -> subprocess.CompletedProcess:
    completed = subprocess.run([str(a) for a in args], cwd=str(cwd) if cwd else None,
                               input=stdin, capture_output=True, timeout=timeout, check=False)
    if check and completed.returncode != 0:
        raise SystemExit(f"step failed ({completed.returncode}): {' '.join(map(str, args[:3]))}: "
                         f"{completed.stderr.decode(errors='replace')[-800:]}")
    return completed


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def set_key(document: str, key: str, value: str) -> str:
    pattern = re.compile(rf"^{re.escape(key)} = .*$", re.M)
    if not pattern.search(document):
        raise SystemExit(f"example has no `{key} =` line")
    return pattern.sub(lambda _: f"{key} = {value}", document, count=1)


def tq(path: Path | str) -> str:
    return json.dumps(str(path))


def resp(host: str, port: int, parts: list[str]) -> bytes:
    request = f"*{len(parts)}\r\n".encode()
    for part in parts:
        data = part.encode()
        request += f"${len(data)}\r\n".encode() + data + b"\r\n"
    with socket.create_connection((host, port), timeout=10) as sock:
        sock.sendall(request)
        sock.shutdown(socket.SHUT_WR)
        reply = b""
        while True:
            chunk = sock.recv(65536)
            if not chunk:
                return reply
            reply += chunk


def delete_namespace(host: str, port: int, namespace: str) -> int:
    prefix = f"tunnel-catalog:{namespace}:"
    cursor, total = "0", 0
    while True:
        text = resp(host, port, ["SCAN", cursor, "MATCH", f"{prefix}*", "COUNT", "1000"]).decode(
            errors="replace")
        lines = text.split("\r\n")
        cursor = lines[2] if len(lines) > 2 else "0"
        keys = [line for line in lines if line.startswith(prefix)]
        if keys:
            resp(host, port, ["DEL", *keys])
            total += len(keys)
        if cursor == "0":
            return total


def percentile(values: list[float], pct: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, int(round(pct / 100.0 * len(ordered) + 0.5)) - 1))
    return ordered[index]


# ------------------------------------------------------ child processes

def _child_setup() -> None:
    """Runs in each child before exec: on Linux, ask for SIGTERM when the
    harness dies (the parent-death signal survives exec).  Children are also
    started in their own session (process group), which `stop_group` kills."""
    if sys.platform.startswith("linux"):
        try:
            import ctypes
            ctypes.CDLL("libc.so.6", use_errno=True).prctl(1, signal.SIGTERM)  # PR_SET_PDEATHSIG
        except OSError:
            pass


def spawn(args: list[str], **kwargs) -> subprocess.Popen:
    """Start a harness child in its own process group.  Call only from the
    main thread: the Linux parent-death signal follows the spawning thread."""
    assert threading.current_thread() is threading.main_thread(), "spawn from the main thread"
    return subprocess.Popen(args, start_new_session=True, preexec_fn=_child_setup, **kwargs)


def stop_group(proc: subprocess.Popen | None, timeout: float = 15) -> None:
    """SIGTERM the child's whole process group, then SIGKILL it if it lingers."""
    if proc is None:
        return
    try:
        os.killpg(proc.pid, signal.SIGCONT)
        os.killpg(proc.pid, signal.SIGTERM)
    except (ProcessLookupError, PermissionError):
        pass
    try:
        proc.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        pass
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        pass
    try:
        proc.wait(timeout=5)
    except subprocess.TimeoutExpired:
        pass


# ------------------------------------------------------- the TLS forwarder

async def _pump(reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
    try:
        while True:
            data = await reader.read(65536)
            if not data:
                break
            writer.write(data)
            await writer.drain()
    except (OSError, asyncio.IncompleteReadError, ssl.SSLError):
        pass
    finally:
        try:
            writer.close()
        except OSError:
            pass


def forwarder_main(args: argparse.Namespace) -> None:
    """A TLS listener in front of a plaintext Redis, so `rediss://` works."""
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(args.cert, args.key)
    upstream_host, upstream_port = args.upstream.rsplit(":", 1)

    async def handle(reader, writer):
        try:
            up_reader, up_writer = await asyncio.open_connection(upstream_host, int(upstream_port))
        except OSError:
            writer.close()
            return
        await asyncio.gather(_pump(reader, up_writer), _pump(up_reader, writer))

    async def main():
        # The relay dials `localhost`, which may resolve to ::1 first; listen
        # on both loopback families where the host has them.
        hosts = ["127.0.0.1"]
        if socket.has_ipv6:
            try:
                with socket.socket(socket.AF_INET6) as probe:
                    probe.bind(("::1", 0))
                hosts.append("::1")
            except OSError:
                pass
        server = await asyncio.start_server(handle, hosts, args.port, ssl=context)
        print(f"forwarder listening port={args.port}", flush=True)
        async with server:
            await server.serve_forever()

    asyncio.run(main())


# --------------------------------------------------------------- the stack

class Stack:
    """One relay, its Redis TLS forwarder and its synthetic devices."""

    def __init__(self, bins: Path, run_dir: Path, redis: tuple[str, int], tag: str,
                 nonce: str, rotation: tuple[int, int, int] = (300, 10, 30),
                 relay_extra: str = ""):
        self.bins = bins
        self.run_dir = run_dir
        self.work = run_dir / "work"
        self.work.mkdir(parents=True, exist_ok=True)
        self.redis = redis
        self.nonce = nonce
        self.namespace = f"{tag}-{nonce}"
        self.rotation = rotation
        self.relay_extra = relay_extra
        self.relay: subprocess.Popen | None = None
        self.relay_procs: list[subprocess.Popen] = []
        self.forwarder: subprocess.Popen | None = None
        self.devices: dict[str, dict] = {}
        self.users: dict[str, dict] = {}
        self.relay_starts = 0
        self.events = (run_dir / "events.jsonl").open("a", buffering=1)
        self.tokens: dict[tuple[str, str], tuple[float, str]] = {}
        self.token_lock = threading.Lock()

    # -- events
    def event(self, name: str, /, **fields) -> None:
        record = {"t": round(time.time(), 3), "at": now_iso(), "event": name,
                  "load1": round(os.getloadavg()[0], 2), **fields}
        self.events.write(json.dumps(record) + "\n")
        print(f"[{record['at']}] {name} {json.dumps(fields)}", flush=True)

    # -- PKI and issuer
    def pki(self) -> None:
        w = self.work
        run(["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "3",
             "-subj", "/CN=m6-03-soak synthetic server CA", "-addext",
             "basicConstraints=critical,CA:TRUE", "-addext", "keyUsage=critical,keyCertSign,cRLSign",
             "-keyout", w / "server-ca-key.pem", "-out", w / "server-ca.pem"])
        (w / "server-ext.cnf").write_text(
            "basicConstraints=CA:FALSE\nkeyUsage=digitalSignature,keyEncipherment\n"
            "extendedKeyUsage=serverAuth\nsubjectAltName=IP:127.0.0.1,DNS:localhost\n"
            "subjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid,issuer\n")
        run(["openssl", "req", "-new", "-newkey", "rsa:2048", "-nodes", "-subj", "/CN=localhost",
             "-keyout", w / "server-key.pem", "-out", w / "server.csr"])
        run(["openssl", "x509", "-req", "-in", w / "server.csr", "-CA", w / "server-ca.pem",
             "-CAkey", w / "server-ca-key.pem", "-CAcreateserial", "-days", "2",
             "-extfile", w / "server-ext.cnf", "-out", w / "server-cert.pem"])
        run(["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "3",
             "-subj", "/CN=m6-03-soak synthetic device CA",
             "-keyout", w / "device-ca-key.pem", "-out", w / "device-ca.pem"])
        run(["openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048",
             "-out", w / "issuer-key.pem"])
        modulus = run(["openssl", "rsa", "-in", w / "issuer-key.pem", "-noout", "-modulus"]
                      ).stdout.decode().strip().split("=", 1)[1]
        (w / "jwks.json").write_text(json.dumps({"keys": [{
            "kty": "RSA", "kid": "m6-03-soak", "alg": "RS256", "use": "sig",
            "n": b64url(bytes.fromhex(modulus)), "e": "AQAB"}]}))

    def token(self, subject: str, scope: str, min_remaining: float = 60) -> str:
        """A 300-second access token, re-signed when `min_remaining` seconds
        or fewer remain."""
        if min_remaining > 240:
            raise ValueError("a 300 s token cannot cover more than 240 s with margin")
        with self.token_lock:
            cached = self.tokens.get((subject, scope))
            if cached and cached[0] - time.time() > min_remaining:
                return cached[1]
            now = int(time.time())
            header = b64url(json.dumps({"alg": "RS256", "typ": "JWT", "kid": "m6-03-soak"}).encode())
            claims = b64url(json.dumps({"iss": ISSUER, "aud": AUDIENCE, "sub": subject,
                                        "iat": now, "exp": now + 300, "scope": scope}).encode())
            signing = f"{header}.{claims}".encode()
            sig = run(["openssl", "dgst", "-sha256", "-sign", self.work / "issuer-key.pem"],
                      stdin=signing).stdout
            value = f"{header}.{claims}.{b64url(sig)}"
            self.tokens[(subject, scope)] = (now + 300, value)
            return value

    # -- forwarder
    def start_forwarder(self) -> None:
        self.forwarder_port = free_port()
        log = (self.run_dir / "forwarder.log").open("w")
        log.write(f"nonce={self.nonce} head={head_sha()} forwarder\n")
        log.flush()
        self.forwarder = spawn(
            [sys.executable, __file__, "forwarder", "--cert", str(self.work / "server-cert.pem"),
             "--key", str(self.work / "server-key.pem"), "--port", str(self.forwarder_port),
             "--upstream", f"{self.redis[0]}:{self.redis[1]}"],
            stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)
        deadline = time.time() + 15
        while time.time() < deadline:
            try:
                with socket.create_connection(("127.0.0.1", self.forwarder_port), timeout=1):
                    return
            except OSError:
                time.sleep(0.1)
        raise SystemExit("forwarder did not listen")

    # -- relay
    def write_relay_config(self) -> None:
        self.consumer_port = free_port()
        self.device_port = free_port()
        self.metrics_port = free_port()
        doc = (REPO / "examples" / "m1-relay.toml").read_text()
        doc = "\n".join(line for line in doc.split("\n") if not line.startswith("boot_id ="))
        w = self.work
        for key, value in (
            ("consumer_bind", json.dumps(f"127.0.0.1:{self.consumer_port}")),
            ("device_bind", json.dumps(f"127.0.0.1:{self.device_port}")),
            ("oidc_issuer", json.dumps(ISSUER)),
            ("oidc_jwks_path", tq(w / "jwks.json")),
            ("redis_url", json.dumps(f"rediss://localhost:{self.forwarder_port}/0")),
            ("redis_namespace", json.dumps(self.namespace)),
            ("device_tls_cert_chain", tq(w / "server-cert.pem")),
            ("device_tls_private_key", tq(w / "server-key.pem")),
            ("device_tls_client_ca", tq(w / "device-ca.pem")),
            ("consumer_tls_cert_chain", tq(w / "server-cert.pem")),
            ("consumer_tls_private_key", tq(w / "server-key.pem")),
            ("deployment_incarnation", json.dumps(self.namespace)),
            ("interval_seconds", str(self.rotation[0])),
            ("handshake_timeout_seconds", str(self.rotation[1])),
            ("overlap_seconds", str(self.rotation[2])),
        ):
            doc = set_key(doc, key, value)
        top = (f"redis_tls_root_ca_path = {tq(w / 'server-ca.pem')}\n"
               f"metrics_bind = \"127.0.0.1:{self.metrics_port}\"\n{self.relay_extra}")
        doc = f"{top}{doc}\n[http_forward]\nprofiles = [\"{MCP_PROFILE}\"]\n"
        self.relay_config = w / "relay.toml"
        self.relay_config.write_text(doc)

    def relay_cmd(self, *args: str) -> str:
        completed = run([self.bins / "tunnel-relay", *args, "--config", self.relay_config])
        return completed.stdout.decode()

    def start_relay(self, wait: bool = True) -> float:
        self.relay_starts += 1
        log = (self.run_dir / f"relay-{self.relay_starts}.log").open("w")
        log.write(f"nonce={self.nonce} head={head_sha()} relay start={self.relay_starts}\n")
        log.flush()
        started = time.time()
        self.relay = spawn(
            ["nice", "-n", "10", str(self.bins / "tunnel-relay"), "serve", "--config",
             str(self.relay_config)], stdout=log, stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL, env={**os.environ, "RUST_LOG": "warn"})
        self.relay_procs.append(self.relay)
        if wait:
            deadline = time.time() + 30
            path = self.run_dir / f"relay-{self.relay_starts}.log"
            while time.time() < deadline:
                if "tunnel-relay listening" in path.read_text(errors="replace"):
                    break
                if self.relay.poll() is not None:
                    raise SystemExit(f"relay exited: {path.read_text()[-1500:]}")
                time.sleep(0.1)
            else:
                raise SystemExit("relay not listening within 30 s")
        return time.time() - started

    # -- catalog
    def provision(self) -> None:
        """First device (`a`), first user and the echo service, from the shipped records."""
        self.write_relay_config()
        records = (REPO / "examples" / "m6-catalog.toml").read_text()
        ids = {table: re.search(rf"^\[{table}\]\nid = \"([^\"]+)\"", records, re.M).group(1)
               for table in ("tenant", "user", "device", "service")}
        subject = re.search(r'^oidc_subject = "([^"]+)"', records, re.M).group(1)
        self.tenant = ids["tenant"]
        self.users["a"] = {"id": ids["user"], "subject": subject}
        device_dir = self.new_device_dir("a", ids["device"], {ids["service"]: "echo"})
        (device_dir / "catalog.toml").write_text(records)
        # A fresh CI runner's first Redis connection has failed at
        # connection_establishment (class=io) before any write; retry that
        # stage only, and record every retry.
        for attempt in range(1, 6):
            completed = run([self.bins / "tunnel-relay", "activate-first-incarnation", "--config",
                             self.relay_config], check=False)
            if completed.returncode == 0:
                break
            stderr = completed.stderr.decode(errors="replace")
            if attempt == 1:
                self.event("activate-diagnostics", **self.redis_diagnostics())
            if "stage=connection_establishment" not in stderr or attempt == 5:
                raise SystemExit(f"activate-first-incarnation failed: {stderr[-600:]}")
            self.event("activate-retry", attempt=attempt, stderr=stderr.strip()[-200:])
            time.sleep(3)
        self.relay_cmd("provision-catalog", "--records", str(device_dir / "catalog.toml"))
        self.devices["a"]["echo"] = ids["service"]
        self.event("provisioned", namespace=self.namespace, device="a")

    def new_device_dir(self, name: str, device_id: str, exports: dict[str, str]) -> Path:
        d = self.work / f"device-{name}"
        d.mkdir(exist_ok=True)
        doc = (REPO / "examples" / "m1-client.toml").read_text()
        doc = set_key(doc, "device_id", json.dumps(device_id))
        doc = set_key(doc, "relay_url",
                      json.dumps(f"wss://127.0.0.1:{self.device_port}/v1/tunnel/control"))
        for key, value in zip(("interval_seconds", "handshake_timeout_seconds", "overlap_seconds"),
                              self.rotation):
            doc = set_key(doc, key, str(value))
        # Replace the example's single export table with this device's exports.
        lines = doc.split("\n")
        start = next(i for i, line in enumerate(lines) if line.startswith("[exports."))
        end = next((i for i in range(start, len(lines)) if not lines[i].strip()), len(lines))
        tables = []
        for service, kind in exports.items():
            if kind == "echo":
                tables.append(f"[exports.\"{service}\"]\ntype = \"echo\"\n"
                              f"device_canary = \"{CANARY.decode()}\"\n")
            else:
                ws = d / "mcp-workspace"
                ws.mkdir(exist_ok=True)
                tables.append(
                    f"[exports.\"{service}\"]\ntype = \"http-forward\"\n\n"
                    f"[exports.\"{service}\".mcp]\nprofile = \"{MCP_PROFILE}\"\n\n"
                    f"[exports.\"{service}\".mcp.backend]\nkind = \"stdio\"\n"
                    f"command = {tq(self.bins / 'tunnel-mcp-fixture')}\nargs = [\"stdio\"]\n"
                    f"workspace = {tq(ws)}\n")
        doc = "\n".join(lines[:start] + ["\n".join(tables).rstrip()] + lines[end:]) + "\n"
        config = d / "client.toml"
        config.write_text(doc)
        run([self.bins / "tunnel-client", "credentials", "create", "--config", config,
             "--csr-out", "device.csr"])
        (d / "ext.cnf").write_text(
            "basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=clientAuth\n"
            f"subjectAltName=URI:urn:agent-tunnel:device:{device_id}\n")
        run(["openssl", "x509", "-req", "-in", d / "device.csr", "-CA", self.work / "device-ca.pem",
             "-CAkey", self.work / "device-ca-key.pem", "-CAcreateserial", "-days", "2",
             "-extfile", d / "ext.cnf", "-out", d / "device-cert.pem"])
        run([self.bins / "tunnel-client", "credentials", "import", "--config", config,
             "--certificate", "device-cert.pem", "--server-ca", self.work / "server-ca.pem"])
        self.devices[name] = {"id": device_id, "dir": d, "config": config, "proc": None,
                              "starts": 0, "exports": dict(exports)}
        return d

    def redis_diagnostics(self) -> dict:
        """Which hop refuses: the upstream Redis, or the forwarder per address family."""
        out: dict[str, str] = {}
        try:
            out["upstream_ping"] = resp(self.redis[0], self.redis[1], ["PING"]).decode(errors="replace").strip()
        except OSError as error:
            out["upstream_ping"] = f"error {type(error).__name__}: {error}"
        out["localhost_resolves"] = ",".join(sorted({a[4][0] for a in socket.getaddrinfo(
            "localhost", self.forwarder_port, type=socket.SOCK_STREAM)}))
        for host in ("127.0.0.1", "::1"):
            try:
                with socket.create_connection((host, self.forwarder_port), timeout=3):
                    out[f"forwarder_{host}"] = "connect ok"
            except OSError as error:
                out[f"forwarder_{host}"] = f"error {type(error).__name__}"
        out["forwarder_alive"] = str(self.forwarder.poll() is None)
        return out

    def add_user(self, name: str) -> None:
        user_id, subject = str(uuid.uuid4()), f"m6-03-soak-user-{name}-{self.nonce}"
        doc = self.work / f"user-{name}.toml"
        doc.write_text(f"[user]\ntenant = \"{self.tenant}\"\nid = \"{user_id}\"\n"
                       f"display_name = \"Soak user {name}\"\noidc_subject = \"{subject}\"\n")
        self.relay_cmd("add-user", "--records", str(doc))
        self.users[name] = {"id": user_id, "subject": subject}

    def add_device(self, name: str, owner: str, exports: dict[str, str]) -> None:
        """A device owned by `owner`, with services named `echo`/`mcp` in `exports`."""
        device_id = str(uuid.uuid4())
        services = {str(uuid.uuid4()): kind for kind in exports}
        d = self.new_device_dir(name, device_id, services)
        doc = d / "device.toml"
        doc.write_text(f"[device]\ntenant = \"{self.tenant}\"\nowner = \"{self.users[owner]['id']}\"\n"
                       f"id = \"{device_id}\"\ndisplay_name = \"Soak device {name}\"\n"
                       f"certificate = \"device-cert.pem\"\n")
        self.relay_cmd("add-device", "--records", str(doc))
        for service, kind in services.items():
            self.add_service(name, service, kind)
            self.grant(owner, name, kind)

    def add_service(self, device: str, service: str, kind: str) -> None:
        dev = self.devices[device]
        body = (f"[service]\ntenant = \"{self.tenant}\"\ndevice = \"{dev['id']}\"\n"
                f"id = \"{service}\"\n")
        if kind == "echo":
            body += "type = \"echo\"\ndisplay_name = \"Soak echo\"\noperations = [\"echo:invoke\"]\n"
        else:
            body += ("type = \"http-forward\"\ndisplay_name = \"Soak MCP\"\n"
                     f"operations = [\"http:invoke\"]\nhttp_forward_profile = \"{MCP_PROFILE}\"\n")
        doc = dev["dir"] / f"service-{kind}.toml"
        doc.write_text(body)
        self.relay_cmd("add-service", "--records", str(doc))
        dev[kind] = service
        dev["exports"][service] = kind

    def add_mcp_to_device(self, device: str) -> None:
        """Add an MCP service to an existing device and rewrite its profile's exports."""
        dev = self.devices[device]
        service = str(uuid.uuid4())
        self.add_service(device, service, "mcp")
        ws = dev["dir"] / "mcp-workspace"
        ws.mkdir(exist_ok=True)
        with dev["config"].open("a") as handle:
            handle.write(
                f"\n[exports.\"{service}\"]\ntype = \"http-forward\"\n\n"
                f"[exports.\"{service}\".mcp]\nprofile = \"{MCP_PROFILE}\"\n\n"
                f"[exports.\"{service}\".mcp.backend]\nkind = \"stdio\"\n"
                f"command = {tq(self.bins / 'tunnel-mcp-fixture')}\nargs = [\"stdio\"]\n"
                f"workspace = {tq(ws)}\n")

    def grant(self, user: str, device: str, kind: str) -> None:
        dev = self.devices[device]
        op = "echo:invoke" if kind == "echo" else "http:invoke"
        doc = self.work / f"grant-{user}-{device}-{kind}.toml"
        doc.write_text(f"[grant]\ntenant = \"{self.tenant}\"\nuser = \"{self.users[user]['id']}\"\n"
                       f"device = \"{dev['id']}\"\nservice = \"{dev[kind]}\"\n"
                       f"operations = [\"{op}\"]\n")
        self.relay_cmd("set-grant", "--records", str(doc))

    # -- devices
    def start_device(self, name: str) -> None:
        dev = self.devices[name]
        previous = dev.get("proc")
        if previous is not None and previous.poll() is None:
            # Never orphan a live device by overwriting its handle.
            self.event("device-still-running", device=name, pid=previous.pid)
            stop_group(previous, timeout=10)
        dev["starts"] += 1
        out = (self.run_dir / f"device-{name}-{dev['starts']}.jsonl").open("w")
        err = (self.run_dir / f"device-{name}-{dev['starts']}.stderr.log").open("w")
        err.write(f"nonce={self.nonce} head={head_sha()} device={name} start={dev['starts']}\n")
        err.flush()
        dev["proc"] = spawn(
            ["nice", "-n", "10", str(self.bins / "tunnel-client"), "connect", "--config",
             str(dev["config"]), "--json"], stdout=out, stderr=err, stdin=subprocess.DEVNULL,
            env={**os.environ, "RUST_LOG": "warn"})
        dev.setdefault("all_procs", []).append(dev["proc"])
        self.event("device-start", device=name, start=dev["starts"], pid=dev["proc"].pid)

    def device_sessions(self, name: str) -> tuple[list[str], int, list[dict]]:
        """(distinct session ids, max rotations_completed, raw events) over all starts."""
        sessions, rotations, events = [], 0, []
        for path in sorted(self.run_dir.glob(f"device-{name}-*.jsonl")):
            for line in path.read_text(errors="replace").splitlines():
                try:
                    value = json.loads(line)
                except ValueError:
                    continue
                events.append(value)
                result = value.get("result") if isinstance(value, dict) else None
                if isinstance(result, dict):
                    session = result.get("session_id")
                    if session and session not in sessions:
                        sessions.append(session)
                    rotations = max(rotations, int(result.get("rotations_completed") or 0))
        return sessions, rotations, events

    # -- teardown
    def close(self) -> None:
        # Whole process groups, so a device's MCP children and anything a
        # killed relay left behind go too; each group is signalled even when
        # its leader already exited.
        for dev in self.devices.values():
            for proc in dev.get("all_procs", []):
                stop_group(proc)
        for proc in self.relay_procs + [self.forwarder]:
            stop_group(proc)
        try:
            removed = delete_namespace(self.redis[0], self.redis[1], self.namespace)
            self.event("namespace-deleted", namespace=self.namespace, keys=removed)
        except OSError as error:
            self.event("namespace-delete-failed", error=str(error))
        self.events.close()


